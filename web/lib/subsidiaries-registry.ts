/**
 * Zwraca spółki zależne dla wskazanego podmiotu portfelowego MAP.
 */
export function getSubsidiariesForEntity(parentEntityId: string) {
  return SUBSIDIARIES_REGISTRY.filter(
    (sub) => sub.parentEntityId === parentEntityId || sub.parentEntityId.includes(parentEntityId)
  ).map((sub) => ({
    ...sub,
    tier: sub.tier === 3 || sub.tier === "III_SZCZEBEL_WNUCZKA" ? ("III_SZCZEBEL_WNUCZKA" as const) : ("II_SZCZEBEL_CORKA" as const),
    sharePercent: sub.sharePercent ?? sub.ownershipPercent,
    roleDescription: sub.roleDescription || sub.riskSummary,
    hasDirectMinisterRisk: sub.hasDirectMinisterRisk ?? (sub.riskIndicator === "CRITICAL_SPILLOVER"),
    ministerRiskContext: sub.ministerRiskContext || sub.riskSummary,
  }));
}
